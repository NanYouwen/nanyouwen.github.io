我会把用户反馈分成三种：资料不存在、资料过期、回答引用错误。三种问题需要不同动作，不能都归结为“模型表现不好”。如果反馈持续来自同一份文档，就说明维护流程中有一处缺口，应该修复源资料或更新规则，而不是反复手工改提示词。

